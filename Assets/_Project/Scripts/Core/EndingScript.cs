using System.Collections.Generic;

namespace Jupiter.Core
{
    /// <summary>
    /// The timed text of the ending: what the screen shows, and how dark it is, at each moment. Two variants: the
    /// sample vented (an empty beach at dusk, the names) or kept (a quarantine monitor pulsing at 0.4 Hz, then the
    /// names). Then the credits, then THE END, which stays. Pure C#.
    /// </summary>
    public class EndingScript
    {
        public struct Frame
        {
            public string Text;
            public float Black, TextAlpha;
            public int Size;
        }

        struct Card { public string Text; public float Seconds; public int Size; }

        public static readonly string[] Names =
        {
            "Commander Daniel Ashford", "Dr. Hana Mori", "Luca Ferreira", "Mara Lindqvist", "Dr. Samuel Okafor (returned)",
        };

        public static readonly string[] Credits =
        {
            "JUPITER: THE LAST TRANSMISSION",
            "A game made in Unity 6",
            "Voices synthesised with Piper, using the LibriTTS-R speakers (CC BY 4.0, Koizumi et al.)",
            "Characters built with MakeHuman assets (CC0) and Blender",
            "Every sound, texture and creature generated by the project's own code",
            "Thank you for playing.",
        };

        readonly List<Card> cards = new List<Card>();
        const float Fade = 0.8f;

        public bool Kept { get; }
        public float Duration { get; }

        public EndingScript(bool kept)
        {
            Kept = kept;
            cards.Add(new Card { Text = "", Seconds = 3f, Size = 26 });
            if (kept)
            {
                cards.Add(new Card { Text = "QUARANTINE OBSERVATION 14\n\nSAMPLE M-7: ACTIVE\npulse 0.40 Hz", Seconds = 6f, Size = 22 });
                cards.Add(new Card { Text = "It is still listening.", Seconds = 4f, Size = 26 });
            }
            else
            {
                cards.Add(new Card { Text = "An empty beach at dusk.\nThe tide coming in.", Seconds = 5f, Size = 24 });
            }
            foreach (var n in Names) cards.Add(new Card { Text = n, Seconds = 3f, Size = 30 });
            foreach (var c in Credits) cards.Add(new Card { Text = c, Seconds = 3.5f, Size = c == Credits[0] ? 34 : 22 });
            float d = 0f;
            foreach (var c in cards) d += c.Seconds;
            Duration = d;
        }

        /// <summary>The screen at <paramref name="t"/> seconds: black rises over the first second, each card fades in and out.</summary>
        public Frame At(float t)
        {
            float black = t < 0f ? 0f : t < 1f ? t : 1f;
            if (t >= Duration) return new Frame { Text = "THE END", Black = 1f, TextAlpha = 1f, Size = 40 };
            float start = 0f;
            foreach (var c in cards)
            {
                if (t < start + c.Seconds)
                {
                    float local = t - start;
                    float a = local < Fade ? local / Fade : local > c.Seconds - Fade ? (c.Seconds - local) / Fade : 1f;
                    return new Frame { Text = c.Text, Black = black, TextAlpha = a < 0f ? 0f : a, Size = c.Size };
                }
                start += c.Seconds;
            }
            return new Frame { Text = "THE END", Black = 1f, TextAlpha = 1f, Size = 40 };
        }
    }
}
